# How a day + date + month reads in each language.
DATE_PATTERNS = {
    "en": "{dow} {d} {mon}", "nl": "{dow} {d} {mon}", "fr": "{dow} {d} {mon}",
    "de": "{dow}, {d}. {mon}", "es": "{dow} {d} de {mon}",
}


def fmt_date(lang, d, style="short"):
    lang = lang if lang in LANGS else "en"
    if style == "dow":
        return DAYS_SHORT[lang][d.weekday()]
    if style == "mon":
        return MONTHS_SHORT[lang][d.month - 1]
    if style == "month":
        return ("%s %d" if lang != "es" else "%s de %d") % (MONTHS[lang][d.month - 1], d.year)
    pattern = DATE_PATTERNS[lang]
    if style == "short":
        return pattern.format(dow=DAYS_SHORT[lang][d.weekday()], d=d.day, mon=MONTHS_SHORT[lang][d.month - 1])
    text = pattern.format(dow=DAYS[lang][d.weekday()], d=d.day, mon=MONTHS[lang][d.month - 1])
    if d.year != date.today().year:
        text += " %d" % d.year
    if style == "day":
        delta = (d - date.today()).days
        if delta in (0, 1):
            text = "%s · %s" % (t(lang, "today" if delta == 0 else "tomorrow"), text)
    return text


def money(lang, cents):
    euros, rest = divmod(int(cents), 100)
    amount = "%d" % euros if rest == 0 else "%d%s%02d" % (euros, "." if lang == "en" else ",", rest)
    return "€" + amount if lang in ("en", "nl") else amount + " €"


class _Keep(dict):
    """Leaves placeholders that weren't passed (e.g. {name}, filled in per recipient later) untouched."""
    def __missing__(self, key):
        return "{" + key + "}"


def t(lang, key, **kwargs):
    text = STRINGS.get(lang, STRINGS["en"]).get(key) or STRINGS["en"].get(key, key)
    return text.format_map(_Keep(kwargs)) if kwargs else text


